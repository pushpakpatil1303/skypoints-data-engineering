
-- ============================================================
-- SKYPOINTS DATA QUALITY VALIDATION
-- ============================================================


-- 1. Check mandatory member fields
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        MEMBER_ID IS NULL
        OR TRIM(MEMBER_ID) = ''
    ) AS MISSING_MEMBER_ID,

    COUNT_IF(
        MEMBER_NAME IS NULL
        OR TRIM(MEMBER_NAME) = ''
    ) AS MISSING_MEMBER_NAME,

    COUNT_IF(
        ENROLLMENT_DATE IS NULL
    ) AS MISSING_ENROLLMENT_DATE,

    COUNT_IF(
        COUNTRY IS NULL
        OR TRIM(COUNTRY) = ''
    ) AS MISSING_COUNTRY

FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE;


-- 2. Check duplicate member names (assessment key column)
SELECT
    MEMBER_NAME,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE
WHERE NULLIF(TRIM(MEMBER_NAME), '') IS NOT NULL
GROUP BY MEMBER_NAME
HAVING COUNT(*) > 1
ORDER BY MEMBER_NAME;


-- 3. Check duplicate member IDs within each country
SELECT
    COUNTRY,
    MEMBER_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE
WHERE NULLIF(TRIM(MEMBER_ID), '') IS NOT NULL
GROUP BY COUNTRY, MEMBER_ID
HAVING COUNT(*) > 1
ORDER BY COUNTRY, MEMBER_ID;


-- 4. Check invalid or missing dates
SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        ENROLLMENT_DATE IS NULL
    ) AS INVALID_ENROLLMENT_DATE,

    COUNT_IF(
        LAST_FLIGHT_DATE IS NULL
    ) AS MISSING_LAST_FLIGHT_DATE,

    COUNT_IF(
        DOB IS NULL
    ) AS MISSING_DOB,

    COUNT_IF(
        DOB > CURRENT_DATE()
    ) AS FUTURE_DOB,

    COUNT_IF(
        ENROLLMENT_DATE > CURRENT_DATE()
    ) AS FUTURE_ENROLLMENT_DATE

FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE;


-- 5. Validate AGE and STALE_MEMBER
SELECT
    MEMBER_ID,
    MEMBER_NAME,
    DOB,
    AGE,
    LAST_FLIGHT_DATE,
    STALE_MEMBER
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE
WHERE
    (DOB IS NOT NULL AND AGE IS NULL)
    OR AGE < 0
    OR (
        LAST_FLIGHT_DATE IS NOT NULL
        AND STALE_MEMBER IS NULL
    )
    OR (
        LAST_FLIGHT_DATE IS NOT NULL
        AND STALE_MEMBER <>
            IFF(
                LAST_FLIGHT_DATE < DATEADD(DAY, -90, CURRENT_DATE()),
                TRUE,
                FALSE
            )
    );


-- 6. Check incorrect country assignments
SELECT
    'INDIA' AS TARGET_TABLE,
    COUNT_IF(
        COUNTRY IS NULL OR COUNTRY <> 'IND'
    ) AS INVALID_RECORDS
FROM SKYPOINTS_DB.TARGET.TABLE_INDIA

UNION ALL

SELECT
    'AUSTRALIA',
    COUNT_IF(
        COUNTRY IS NULL
        OR COUNTRY NOT IN ('AU', 'AUS')
    )
FROM SKYPOINTS_DB.TARGET.TABLE_AUSTRALIA

UNION ALL

SELECT
    'USA',
    COUNT_IF(
        COUNTRY IS NULL OR COUNTRY <> 'USA'
    )
FROM SKYPOINTS_DB.TARGET.TABLE_USA

UNION ALL

SELECT
    'PHILIPPINES',
    COUNT_IF(
        COUNTRY IS NULL OR COUNTRY <> 'PHIL'
    )
FROM SKYPOINTS_DB.TARGET.TABLE_PHILIPPINES

UNION ALL

SELECT
    'CANADA',
    COUNT_IF(
        COUNTRY IS NULL OR COUNTRY <> 'CAN'
    )
FROM SKYPOINTS_DB.TARGET.TABLE_CANADA;


-- 7. Find staging members missing from country targets
SELECT
    S.MEMBER_ID,
    S.MEMBER_NAME,
    S.COUNTRY,
    S.SOURCE_FILE
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE S
WHERE
    (S.COUNTRY = 'IND'
        AND NOT EXISTS (
            SELECT 1
            FROM SKYPOINTS_DB.TARGET.TABLE_INDIA T
            WHERE T.MEMBER_ID = S.MEMBER_ID
              AND T.GLOBAL_MEMBER_ID IS NULL
        ))
    OR
    (S.COUNTRY IN ('AU', 'AUS')
        AND NOT EXISTS (
            SELECT 1
            FROM SKYPOINTS_DB.TARGET.TABLE_AUSTRALIA T
            WHERE T.MEMBER_ID = S.MEMBER_ID
              AND T.GLOBAL_MEMBER_ID IS NULL
        ))
    OR
    (S.COUNTRY = 'USA'
        AND NOT EXISTS (
            SELECT 1
            FROM SKYPOINTS_DB.TARGET.TABLE_USA T
            WHERE T.MEMBER_ID = S.MEMBER_ID
              AND T.GLOBAL_MEMBER_ID IS NULL
        ))
    OR
    (S.COUNTRY = 'PHIL'
        AND NOT EXISTS (
            SELECT 1
            FROM SKYPOINTS_DB.TARGET.TABLE_PHILIPPINES T
            WHERE T.MEMBER_ID = S.MEMBER_ID
              AND T.GLOBAL_MEMBER_ID IS NULL
        ))
    OR
    (S.COUNTRY = 'CAN'
        AND NOT EXISTS (
            SELECT 1
            FROM SKYPOINTS_DB.TARGET.TABLE_CANADA T
            WHERE T.MEMBER_ID = S.MEMBER_ID
              AND T.GLOBAL_MEMBER_ID IS NULL
        ))
ORDER BY S.COUNTRY, S.MEMBER_ID;


-- 8. Validate redemption transaction quality
SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,

    COUNT_IF(
        MEMBER_ID IS NULL
        OR TRIM(MEMBER_ID) = ''
    ) AS MISSING_MEMBER_ID,

    COUNT_IF(
        TXN_ID IS NULL
        OR TRIM(TXN_ID) = ''
    ) AS MISSING_TXN_ID,

    COUNT(*) - COUNT(DISTINCT TXN_ID)
        AS DUPLICATE_TXN_ID,

    COUNT_IF(
        TXN_DATE IS NULL
    ) AS MISSING_TXN_DATE,

    COUNT_IF(
        FEED_DATE IS NULL
    ) AS MISSING_FEED_DATE,

    COUNT_IF(
        MILES_REDEEMED IS NULL
        OR MILES_REDEEMED < 0
    ) AS INVALID_MILES

FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS;


-- 9. Find duplicate redemption transactions
SELECT
    TXN_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS
WHERE TXN_ID IS NOT NULL
GROUP BY TXN_ID
HAVING COUNT(*) > 1
ORDER BY TXN_ID;


-- 10. Find redemptions without matching members
SELECT
    R.TXN_ID,
    R.MEMBER_ID,
    R.PARTNER,
    R.MILES_REDEEMED,
    R.STATUS
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS R
WHERE NOT EXISTS (
    SELECT 1
    FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE M
    WHERE M.MEMBER_ID = R.MEMBER_ID
)
ORDER BY R.TXN_ID;


-- 11. Verify assessment flat-file members
SELECT
    MEMBER_NAME,
    MEMBER_ID,
    COUNTRY,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    DOB,
    AGE,
    STALE_MEMBER
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE
WHERE SOURCE_FILE = 'members_sample.txt'
ORDER BY MEMBER_ID;


-- 12. Verify assessment JSON redemption transactions
SELECT
    R.TXN_ID,
    R.MEMBER_ID,
    M.MEMBER_NAME,
    R.FEED_DATE,
    R.TXN_DATE,
    R.PARTNER,
    R.MILES_REDEEMED,
    R.STATUS
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS R
LEFT JOIN SKYPOINTS_DB.STAGING.MEMBER_PROFILE M
    ON R.MEMBER_ID = M.MEMBER_ID
WHERE R.SOURCE_FILE = 'partner_redemptions.json'
ORDER BY R.TXN_ID;


-- 13. Verify global member uniqueness across all countries
SELECT
    GLOBAL_MEMBER_ID,
    COUNT(*) AS COUNTRY_RECORD_COUNT
FROM (
    SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_DB.TARGET.TABLE_INDIA
    UNION ALL
    SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_DB.TARGET.TABLE_USA
    UNION ALL
    SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_DB.TARGET.TABLE_AUSTRALIA
    UNION ALL
    SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_DB.TARGET.TABLE_PHILIPPINES
    UNION ALL
    SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_DB.TARGET.TABLE_CANADA
)
WHERE GLOBAL_MEMBER_ID IS NOT NULL
GROUP BY GLOBAL_MEMBER_ID
HAVING COUNT(*) > 1;
