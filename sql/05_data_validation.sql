
-- Check for missing mandatory member information
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(
        MEMBER_ID IS NULL
        OR TRIM(MEMBER_ID) = ''
    ) AS MISSING_MEMBER_ID,
    COUNT_IF(
        MEMBER_NAME IS NULL
        OR TRIM(MEMBER_NAME) = ''
    ) AS MISSING_MEMBER_NAME,
    COUNT_IF(
        ENROLLMENT_DATE IS NULL
    ) AS MISSING_ENROLLMENT_DATE,
    COUNT_IF(
        COUNTRY IS NULL
        OR TRIM(COUNTRY) = ''
    ) AS MISSING_COUNTRY
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE;



-- Check duplicate member IDs within each country
SELECT
    COUNTRY,
    MEMBER_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE
GROUP BY COUNTRY, MEMBER_ID
HAVING COUNT(*) > 1
ORDER BY COUNTRY, MEMBER_ID;




-- Validate redemption transaction quality
SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,

    COUNT_IF(
        MEMBER_ID IS NULL
        OR TRIM(MEMBER_ID) = ''
    ) AS MISSING_MEMBER_ID,

    COUNT_IF(
        TXN_ID IS NULL
        OR TRIM(TXN_ID) = ''
    ) AS MISSING_TXN_ID,

    COUNT(*) - COUNT(DISTINCT TXN_ID) AS DUPLICATE_TXN_ID,

    COUNT_IF(
        TXN_DATE IS NULL
    ) AS MISSING_TXN_DATE,

    COUNT_IF(
        MILES_REDEEMED IS NULL
        OR MILES_REDEEMED < 0
    ) AS INVALID_MILES

FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS;





-- Check for members routed to the wrong country table
SELECT
    'INDIA' AS TARGET_TABLE,
    COUNT_IF(COUNTRY IS NULL OR COUNTRY <> 'IND') AS INVALID_RECORDS
FROM SKYPOINTS_DB.TARGET.TABLE_INDIA

UNION ALL

SELECT
    'AUSTRALIA',
    COUNT_IF(COUNTRY IS NULL OR COUNTRY <> 'AUS')
FROM SKYPOINTS_DB.TARGET.TABLE_AUSTRALIA

UNION ALL

SELECT
    'USA',
    COUNT_IF(COUNTRY IS NULL OR COUNTRY <> 'USA')
FROM SKYPOINTS_DB.TARGET.TABLE_USA;
