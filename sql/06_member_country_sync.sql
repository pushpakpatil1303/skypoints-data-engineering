-- Verify no global member exists in multiple country tables.

SELECT
    GLOBAL_MEMBER_ID,
    COUNT(*) AS COUNTRY_RECORD_COUNT
FROM (
    SELECT GLOBAL_MEMBER_ID
    FROM TARGET.TABLE_INDIA

    UNION ALL

    SELECT GLOBAL_MEMBER_ID
    FROM TARGET.TABLE_USA

    UNION ALL

    SELECT GLOBAL_MEMBER_ID
    FROM TARGET.TABLE_AUSTRALIA

    UNION ALL

    SELECT GLOBAL_MEMBER_ID
    FROM TARGET.TABLE_PHILIPPINES

    UNION ALL

    SELECT GLOBAL_MEMBER_ID
    FROM TARGET.TABLE_CANADA
)
WHERE GLOBAL_MEMBER_ID IS NOT NULL
GROUP BY GLOBAL_MEMBER_ID
HAVING COUNT(*) > 1;


