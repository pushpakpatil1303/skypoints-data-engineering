
USE DATABASE SKYPOINTS_DB;

BEGIN TRANSACTION;

-- Remove global members from outdated country tables.

DELETE FROM TARGET.TABLE_INDIA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'IND'
       OR COUNTRY IS NULL
);

DELETE FROM TARGET.TABLE_USA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'USA'
       OR COUNTRY IS NULL
);

DELETE FROM TARGET.TABLE_AUSTRALIA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY NOT IN ('AU', 'AUS')
       OR COUNTRY IS NULL
);

DELETE FROM TARGET.TABLE_PHILIPPINES T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'PHIL'
       OR COUNTRY IS NULL
);

DELETE FROM TARGET.TABLE_CANADA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'CAN'
       OR COUNTRY IS NULL
);


-- Insert or update members in their latest country table.

MERGE INTO TARGET.TABLE_INDIA T
USING (
    SELECT *
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY = 'IND'
) S
ON T.GLOBAL_MEMBER_ID = S.GLOBAL_MEMBER_ID
WHEN MATCHED THEN UPDATE SET
    T.MEMBER_ID = S.MEMBER_ID,
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = S.COUNTRY
WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    GLOBAL_MEMBER_ID
)
VALUES (
    S.MEMBER_ID,
    S.MEMBER_NAME,
    S.COUNTRY,
    S.GLOBAL_MEMBER_ID
);


