
USE DATABASE SKYPOINTS_DB;

BEGIN TRANSACTION;

-- Remove globally identified members whose latest country is different.
DELETE FROM TARGET.TABLE_INDIA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'IND'
);

DELETE FROM TARGET.TABLE_USA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'USA'
);

DELETE FROM TARGET.TABLE_AUSTRALIA T
WHERE T.GLOBAL_MEMBER_ID IN (
    SELECT GLOBAL_MEMBER_ID
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY <> 'AUS'
);

-- Insert or update the latest member in the correct country.
MERGE INTO TARGET.TABLE_INDIA T
USING (
    SELECT *
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY = 'IND'
) S
ON T.GLOBAL_MEMBER_ID = S.GLOBAL_MEMBER_ID
WHEN MATCHED THEN UPDATE SET
    T.MEMBER_ID = S.MEMBER_ID,
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = S.COUNTRY
WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, GLOBAL_MEMBER_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, S.COUNTRY, S.GLOBAL_MEMBER_ID
);

MERGE INTO TARGET.TABLE_USA T
USING (
    SELECT *
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY = 'USA'
) S
ON T.GLOBAL_MEMBER_ID = S.GLOBAL_MEMBER_ID
WHEN MATCHED THEN UPDATE SET
    T.MEMBER_ID = S.MEMBER_ID,
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = S.COUNTRY
WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, GLOBAL_MEMBER_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, S.COUNTRY, S.GLOBAL_MEMBER_ID
);

MERGE INTO TARGET.TABLE_AUSTRALIA T
USING (
    SELECT *
    FROM STAGING.LATEST_MEMBER_CHANGES
    WHERE COUNTRY = 'AUS'
) S
ON T.GLOBAL_MEMBER_ID = S.GLOBAL_MEMBER_ID
WHEN MATCHED THEN UPDATE SET
    T.MEMBER_ID = S.MEMBER_ID,
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = S.COUNTRY
WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, GLOBAL_MEMBER_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, S.COUNTRY, S.GLOBAL_MEMBER_ID
);

COMMIT;

-- Verify global members appear in only one country table.
SELECT
    GLOBAL_MEMBER_ID,
    COUNT(*) AS COUNTRY_RECORD_COUNT
FROM (
    SELECT GLOBAL_MEMBER_ID FROM TARGET.TABLE_INDIA
    UNION ALL
    SELECT GLOBAL_MEMBER_ID FROM TARGET.TABLE_USA
    UNION ALL
    SELECT GLOBAL_MEMBER_ID FROM TARGET.TABLE_AUSTRALIA
)
WHERE GLOBAL_MEMBER_ID IS NOT NULL
GROUP BY GLOBAL_MEMBER_ID
HAVING COUNT(*) > 1;
