-- LATEST MEMBER COUNTRY-CHANGE VIEW


CREATE OR REPLACE VIEW SKYPOINTS_DB.STAGING.LATEST_MEMBER_CHANGES AS
SELECT
    GLOBAL_MEMBER_ID,
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    SOURCE_UPDATED_AT
FROM SKYPOINTS_DB.RAW.MEMBER_CHANGE_EVENTS
WHERE GLOBAL_MEMBER_ID IS NOT NULL
  AND SOURCE_UPDATED_AT IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY GLOBAL_MEMBER_ID
    ORDER BY SOURCE_UPDATED_AT DESC, LOAD_TIMESTAMP DESC
) = 1;
