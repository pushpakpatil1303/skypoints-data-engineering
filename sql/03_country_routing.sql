
BEGIN TRANSACTION;

-- INDIA
MERGE INTO SKYPOINTS_DB.TARGET.TABLE_INDIA AS T
USING (
    SELECT *
    FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE
    WHERE COUNTRY = 'IND'
      AND NULLIF(TRIM(MEMBER_ID), '') IS NOT NULL
      AND NULLIF(TRIM(MEMBER_NAME), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY LOAD_TIMESTAMP DESC NULLS LAST, SOURCE_FILE DESC
    ) = 1
) AS S
ON T.MEMBER_ID = S.MEMBER_ID
   AND T.GLOBAL_MEMBER_ID IS NULL

WHEN MATCHED AND (
    T.LOAD_TIMESTAMP IS NULL
    OR S.LOAD_TIMESTAMP >= T.LOAD_TIMESTAMP
) THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.LAST_FLIGHT_DATE = S.LAST_FLIGHT_DATE,
    T.TIER_CODE = S.TIER_CODE,
    T.AGENT_NAME = S.AGENT_NAME,
    T.STATE = S.STATE,
    T.COUNTRY = S.COUNTRY,
    T.POST_CODE = S.POST_CODE,
    T.DOB = S.DOB,
    T.IS_ACTIVE = S.IS_ACTIVE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.LOAD_TIMESTAMP = S.LOAD_TIMESTAMP

WHEN NOT MATCHED THEN INSERT (
    MEMBER_NAME, MEMBER_ID, ENROLLMENT_DATE,
    LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME,
    STATE, COUNTRY, POST_CODE, DOB,
    IS_ACTIVE, AGE, STALE_MEMBER,
    SOURCE_FILE, LOAD_TIMESTAMP, GLOBAL_MEMBER_ID
)
VALUES (
    S.MEMBER_NAME, S.MEMBER_ID, S.ENROLLMENT_DATE,
    S.LAST_FLIGHT_DATE, S.TIER_CODE, S.AGENT_NAME,
    S.STATE, S.COUNTRY, S.POST_CODE, S.DOB,
    S.IS_ACTIVE, S.AGE, S.STALE_MEMBER,
    S.SOURCE_FILE, S.LOAD_TIMESTAMP, NULL
);


