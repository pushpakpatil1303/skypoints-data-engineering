
-- Create the SkyPoints database and schemas
CREATE DATABASE IF NOT EXISTS SKYPOINTS_DB;
USE SKYPOINTS_DB;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_DB.RAW;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_DB.TARGET;


-- RAW member table
CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.RAW.MEMBER_PROFILE (
    MEMBER_NAME VARCHAR(255),
    MEMBER_ID VARCHAR(18),
    ENROLLMENT_DATE VARCHAR(20),
    LAST_FLIGHT_DATE VARCHAR(20),
    TIER_CODE VARCHAR(5),
    AGENT_NAME VARCHAR(255),
    STATE VARCHAR(5),
    COUNTRY VARCHAR(5),
    POST_CODE VARCHAR(20),
    DOB VARCHAR(20),
    IS_ACTIVE VARCHAR(1),
    SOURCE_FILE VARCHAR(255),
    LOAD_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID VARCHAR(36)
);


-- STAGING member table
CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.STAGING.MEMBER_PROFILE (
    MEMBER_NAME VARCHAR(255),
    MEMBER_ID VARCHAR(18),
    ENROLLMENT_DATE DATE,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE VARCHAR(5),
    AGENT_NAME VARCHAR(255),
    STATE VARCHAR(5),
    COUNTRY VARCHAR(5),
    POST_CODE VARCHAR(20),
    DOB DATE,
    IS_ACTIVE VARCHAR(1),
    AGE INT,
    STALE_MEMBER BOOLEAN,
    SOURCE_FILE VARCHAR(255),
    LOAD_TIMESTAMP TIMESTAMP_NTZ
);


-- Create country-specific target tables
CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.TARGET.TABLE_INDIA
LIKE SKYPOINTS_DB.STAGING.MEMBER_PROFILE;

CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.TARGET.TABLE_USA
LIKE SKYPOINTS_DB.STAGING.MEMBER_PROFILE;

CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.TARGET.TABLE_AUSTRALIA
LIKE SKYPOINTS_DB.STAGING.MEMBER_PROFILE;


CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.TARGET.TABLE_PHILIPPINES
LIKE SKYPOINTS_DB.TARGET.TABLE_INDIA;

CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.TARGET.TABLE_CANADA
LIKE SKYPOINTS_DB.TARGET.TABLE_INDIA;


-- RAW redemption table for original JSON
CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.RAW.REDEMPTION_JSON (
    RAW_DATA VARIANT,
    SOURCE_FILE VARCHAR(255),
    LOAD_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- STAGING redemption table for flattened transactions
CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.STAGING.REDEMPTION_TRANSACTIONS (
    MEMBER_ID VARCHAR(18),
    FEED_DATE DATE,
    TXN_ID VARCHAR(50),
    TXN_DATE DATE,
    PARTNER VARCHAR(255),
    MILES_REDEEMED NUMBER(18,0),
    STATUS VARCHAR(20),
    SOURCE_FILE VARCHAR(255),
    LOAD_TIMESTAMP TIMESTAMP_NTZ
);


-- Final redemption transactions table
CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS
LIKE SKYPOINTS_DB.STAGING.REDEMPTION_TRANSACTIONS;




-- country tables to support the global member identity.
ALTER TABLE TARGET.TABLE_INDIA
ADD COLUMN IF NOT EXISTS GLOBAL_MEMBER_ID VARCHAR(50);

ALTER TABLE TARGET.TABLE_USA
ADD COLUMN IF NOT EXISTS GLOBAL_MEMBER_ID VARCHAR(50);

ALTER TABLE TARGET.TABLE_AUSTRALIA
ADD COLUMN IF NOT EXISTS GLOBAL_MEMBER_ID VARCHAR(50);

ALTER TABLE SKYPOINTS_DB.TARGET.TABLE_PHILIPPINES
ADD COLUMN IF NOT EXISTS GLOBAL_MEMBER_ID VARCHAR(50);

ALTER TABLE SKYPOINTS_DB.TARGET.TABLE_CANADA
ADD COLUMN IF NOT EXISTS GLOBAL_MEMBER_ID VARCHAR(50);
-- timestamped member country-change events.
CREATE TABLE IF NOT EXISTS RAW.MEMBER_CHANGE_EVENTS (
    GLOBAL_MEMBER_ID VARCHAR(50),
    MEMBER_ID VARCHAR(18),
    MEMBER_NAME VARCHAR(255),
    COUNTRY VARCHAR(5),
    SOURCE_UPDATED_AT TIMESTAMP_NTZ,
    LOAD_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
