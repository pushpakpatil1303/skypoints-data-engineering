-- Flatten and transform nested redemption transactions
INSERT OVERWRITE INTO SKYPOINTS_DB.STAGING.REDEMPTION_TRANSACTIONS (
    MEMBER_ID,
    FEED_DATE,
    TXN_ID,
    TXN_DATE,
    PARTNER,
    MILES_REDEEMED,
    STATUS,
    SOURCE_FILE,
    LOAD_TIMESTAMP
)
SELECT
    R.RAW_DATA:member_id::VARCHAR AS MEMBER_ID,

    COALESCE(
        TRY_TO_DATE(R.RAW_DATA:feed_date::VARCHAR, 'YYYY-MM-DD'),
        TRY_TO_DATE(R.RAW_DATA:feed_date::VARCHAR, 'YYYYMMDD')
    ) AS FEED_DATE,

    T.VALUE:txn_id::VARCHAR AS TXN_ID,

    COALESCE(
        TRY_TO_DATE(T.VALUE:txn_date::VARCHAR, 'YYYY-MM-DD'),
        TRY_TO_DATE(T.VALUE:txn_date::VARCHAR, 'YYYYMMDD')
    ) AS TXN_DATE,

    T.VALUE:partner::VARCHAR AS PARTNER,
    TRY_TO_NUMBER(T.VALUE:miles_redeemed::VARCHAR) AS MILES_REDEEMED,
    T.VALUE:status::VARCHAR AS STATUS,
    R.SOURCE_FILE,
    R.LOAD_TIMESTAMP

FROM SKYPOINTS_DB.RAW.REDEMPTION_JSON R,
LATERAL FLATTEN(
    INPUT => COALESCE(
        R.RAW_DATA:redemptions,
        R.RAW_DATA:transactions
    )
) T
WHERE T.VALUE:txn_id IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY T.VALUE:txn_id::VARCHAR
    ORDER BY R.LOAD_TIMESTAMP DESC, R.SOURCE_FILE DESC
) = 1;


-- Load processed transactions into the target table
INSERT OVERWRITE INTO SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS (
    MEMBER_ID,
    FEED_DATE,
    TXN_ID,
    TXN_DATE,
    PARTNER,
    MILES_REDEEMED,
    STATUS,
    SOURCE_FILE,
    LOAD_TIMESTAMP
)
SELECT
    MEMBER_ID,
    FEED_DATE,
    TXN_ID,
    TXN_DATE,
    PARTNER,
    MILES_REDEEMED,
    STATUS,
    SOURCE_FILE,
    LOAD_TIMESTAMP
FROM SKYPOINTS_DB.STAGING.REDEMPTION_TRANSACTIONS;


-- Verify flattened redemption transactions
SELECT
    MEMBER_ID,
    FEED_DATE,
    TXN_ID,
    TXN_DATE,
    PARTNER,
    MILES_REDEEMED,
    STATUS
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS
ORDER BY TXN_ID;



-- Verify each redemption transaction against its member profile
SELECT
    R.TXN_ID,
    R.MEMBER_ID,
    M.MEMBER_NAME,
    M.COUNTRY,
    R.FEED_DATE,
    R.TXN_DATE,
    R.PARTNER,
    R.MILES_REDEEMED,
    R.STATUS
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS R
LEFT JOIN SKYPOINTS_DB.STAGING.MEMBER_PROFILE M
    ON R.MEMBER_ID = M.MEMBER_ID
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY R.TXN_ID
    ORDER BY M.LOAD_TIMESTAMP DESC NULLS LAST
) = 1
ORDER BY R.TXN_ID;


-- Identify redemption transactions without a matching member
SELECT
    R.TXN_ID,
    R.MEMBER_ID,
    R.PARTNER,
    R.MILES_REDEEMED
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS R
WHERE NOT EXISTS (
    SELECT 1
    FROM SKYPOINTS_DB.STAGING.MEMBER_PROFILE M
    WHERE M.MEMBER_ID = R.MEMBER_ID
);


-- Check for duplicate redemption transaction IDs
SELECT
    TXN_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.TARGET.REDEMPTION_TRANSACTIONS
GROUP BY TXN_ID
HAVING COUNT(*) > 1;
